const testRelayRootAgentGemini = "gemini"

func TestInitCommand_CreatesRelayConfigWithSelectedRootAgent(t *testing.T) {
	workingDir := t.TempDir()
	prevWD, err := os.Getwd()
	if err != nil {
		t.Fatalf("get wd: %v", err)
	}
	t.Cleanup(func() {
		_ = os.Chdir(prevWD)
	})
	if err := os.Chdir(workingDir); err != nil {
		t.Fatalf("chdir: %v", err)
	}

	prevInput := relayInitInput
	prevOutput := relayInitOutput
	prevInteractive := relayInitIsInteractive
	t.Cleanup(func() {
		relayInitInput = prevInput
		relayInitOutput = prevOutput
		relayInitIsInteractive = prevInteractive
	})

	relayInitInput = strings.NewReader("")
	relayInitOutput = &bytes.Buffer{}
	relayInitIsInteractive = func() bool { return false }

	cmd := initCommand()
	cmd.SetArgs([]string{"--relay-root-agent", testRelayRootAgentGemini})
	if err := cmd.Execute(); err != nil {
		t.Fatalf("init command failed: %v", err)
	}

	configPath := filepath.Join(workingDir, ".norma", relayConfigFileName)
	content, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatalf("read config: %v", err)
	}

	var doc map[string]any
	if err := yaml.Unmarshal(content, &doc); err != nil {
		t.Fatalf("unmarshal config: %v", err)
	}
	relaySection, ok := toStringAnyMap(doc["relay"])
	if !ok {
		t.Fatalf("relay section missing in %s", configPath)
	}
	if got := relaySection["root_agent"]; got != testRelayRootAgentGemini {
		t.Fatalf("relay.root_agent = %#v, want %s", got, testRelayRootAgentGemini)
	}
	telegramSection, ok := toStringAnyMap(relaySection["telegram"])
	if !ok {
		t.Fatal("relay.telegram section missing in generated config")
	}
	if got := telegramSection["token"]; got != "" {
		t.Fatalf("relay.telegram.token = %#v, want empty string in non-interactive mode", got)
	}

	normaSection, ok := toStringAnyMap(doc["norma"])
	if !ok {
		t.Fatal("norma section missing in generated config")
	}
	agents, ok := toStringAnyMap(normaSection["agents"])
	if !ok {
		t.Fatal("norma.agents missing in generated config")
	}
	if _, ok := agents["custom_generic"]; ok {
		t.Fatal("norma.agents.custom_generic must not be generated by relay init")
	}
	if _, ok := agents["custom_generic_acp_agent"]; ok {
		t.Fatal("norma.agents.custom_generic_acp_agent must not be generated by relay init")
	}

	for _, key := range []string{
		"root_agent",
		"telegram",
		"auth",
		"logger",
		"working_dir",
		"state_dir",
		"workspace",
		"mcp",
		"internal_mcp",
	} {
		if _, ok := relaySection[key]; !ok {
			t.Fatalf("relay.%s is missing in generated config", key)
		}
	}
	mcpSection, ok := toStringAnyMap(relaySection["mcp"])
	if !ok {
		t.Fatal("relay.mcp section is missing or invalid")
	}
	if _, ok := mcpSection["address"]; !ok {
		t.Fatal("relay.mcp.address is missing in generated config")
	}
}

