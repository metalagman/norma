func TestInitCommand_FailsWhenConfigAlreadyExists(t *testing.T) {
	workingDir := t.TempDir()
	prevWD, err := os.Getwd()
	if err != nil {
		t.Fatalf("get wd: %v", err)
	}
	t.Cleanup(func() {
		_ = os.Chdir(prevWD)
	})
	if err := os.Chdir(workingDir); err != nil {
		t.Fatalf("chdir: %v", err)
	}

	configPath := filepath.Join(workingDir, ".norma", relayConfigFileName)
	if err := os.MkdirAll(filepath.Dir(configPath), 0o700); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(configPath, []byte("relay:\n  root_agent: existing\n"), 0o600); err != nil {
		t.Fatalf("write existing config: %v", err)
	}

	cmd := initCommand()
	cmd.SetArgs([]string{"--relay-root-agent", testRelayRootAgentGemini})
	err = cmd.Execute()
	if err == nil {
		t.Fatal("expected error when relay config already exists")
	}
	if !strings.Contains(err.Error(), "already exists") {
		t.Fatalf("unexpected error: %v", err)
	}
}

